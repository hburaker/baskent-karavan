export type RouteKey = keyof typeof routes;

const prefix = (lang: Lang) => (lang === defaultLang ? '' : `/${lang}`);
const clean = (p: string) => (p.replace(/\/+/g, '/').replace(/\/?$/, '/') || '/');

/** Sayfa anahtarına göre dil uyumlu URL üretir. */
export const url = (lang: Lang, key: RouteKey, hash = '') => clean(`${prefix(lang)}/${routes[key][lang]}`) + hash;
/** Ürün sayfası URL'si (TR: /prime-400/, EN: /en/prime-400/) */
export const productUrl = (lang: Lang, slug: string) => clean(`${prefix(lang)}/${slug}`);
/** Blog yalnızca Türkçe */
export const postUrl = (slug: string) => `/${slug}/`;

export const formatPrice = (n: number, lang: Lang) =>
  `${new Intl.NumberFormat(langMeta[lang].locale).format(n)} TL`;

